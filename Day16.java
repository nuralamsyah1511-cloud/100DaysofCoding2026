public class Day16 {
    public static void main(String[] args) {
        //Day 16 
        //Operasi Aritmetika Modulus atau Sisa Bagi(%)

        int a = 30;
        int b = 10;

        int hasil1 = a % b;
        System.out.println("Hasil modulus 30 % 10 adalah:"+hasil1);
        
        int hasil2 = b % a;
        System.out.println("Hasil modulus 10 % 30 adalah:"+hasil2);
    }
    
}
