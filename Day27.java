public class Day27 {
    public static void main(String[] args) {

        int angka = 10;

        System.out.println("Nilai awal = " + angka);

        angka++;
        System.out.println("Setelah increment = " + angka);

        angka--;
        System.out.println("Setelah decrement = " + angka);
    }
    
}
