public class Day80 {
    public static void main(String[] args) {
        // Day80
        // Akses Elemen Array Dengan Indeks

        int[] angka = {10, 20, 30, 40, 50};

        for (int i = 0; i < angka.length; i++) {
            System.out.println("Indeks " + i + " = " + angka[i]);
        }

        System.out.println("Elemen indeks 2: " + angka[2]);
    }
}
