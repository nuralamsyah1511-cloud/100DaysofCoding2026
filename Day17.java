public class Day17 {
    public static void main(String[] args) {
        //Day 17
        //Operator Penguasaan [=,+=,-=,*=,/=,%/]

        int angka = 10;

        System.out.println("Nilai awal = " + angka);

        // Operator =
        angka = 20;
        System.out.println("Setelah angka = 20 : " + angka);

        // Operator +=
        angka += 5;
        System.out.println("Setelah angka += 5 : " + angka);

        // Operator -=
        angka -= 3;
        System.out.println("Setelah angka -= 3 : " + angka);

        // Operator *=
        angka *= 2;
        System.out.println("Setelah angka *= 2 : " + angka);

        // Operator /=
        angka /= 4;
        System.out.println("Setelah angka /= 4 : " + angka);

        // Operator %=
        angka %= 3;
        System.out.println("Setelah angka %= 3 : " + angka);
        
    }
}
